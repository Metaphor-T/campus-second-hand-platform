// 在仓库根目录运行；工具安装与复现步骤见 docs/accessibility-test-cases.md。
const { chromium } = require('../../.local-backups/a11y-tools/node_modules/playwright')
const { AxeBuilder } = require('../../.local-backups/a11y-tools/node_modules/@axe-core/playwright')
const fs = require('node:fs')
const assert = require('node:assert/strict')
const out = '.local-backups/accessibility-results'
fs.mkdirSync(out, { recursive: true })
;(async () => {
  const browser = await chromium.launch({ channel: 'msedge', headless: true })
  const context = await browser.newContext({ viewport: { width: 1440, height: 1000 }, reducedMotion: 'reduce' })
  const page = await context.newPage()
  const results = [], errors = []
  page.on('pageerror', e => errors.push(e.message))
  try {
    await page.goto('http://127.0.0.1:21091/login')
    await page.getByRole('button', { name: /阅读设置·字号/ }).click()
    for (const scale of [1, 1.25, 1.5, 2]) {
      await page.locator(`input.font-scale-option:visible[value="${scale}"]`).check()
      assert.equal(await page.locator('html').getAttribute('data-font-scale'), String(scale))
      await page.waitForFunction(value => Math.abs(parseFloat(getComputedStyle(document.querySelector('#auth-account')).fontSize) - 13.3 * value) < .1, scale)
      const size = await page.locator('#auth-account').evaluate(el => parseFloat(getComputedStyle(el).fontSize))
      results.push({ test: 'login-scale', scale, inputFont: size })
    }
    await page.reload()
    assert.equal(await page.locator('html').getAttribute('data-font-scale'), '2')
    await page.getByRole('link', { name: '立即注册', exact: true }).click()
    assert.equal(await page.locator('html').getAttribute('data-font-scale'), '2')
    await page.getByRole('button', { name: '立即注册', exact: true }).click()
    assert.ok(await page.locator('.auth-error').innerText())
    results.push({ test: 'persistence-navigation-and-inline-error', passed: true })
    const loginResponse = await context.request.post('http://127.0.0.1:21090/user/login', { data: { account: 'player2_tester', password: 'Player2Test!2026' } })
    const login = await loginResponse.json()
    assert.equal(login.code, 200)
    await page.evaluate(data => { localStorage.setItem('TOKEN', data.token); localStorage.setItem('ROLE', data.role) }, login.data)
    for (const width of [1440, 768, 320]) {
      await page.setViewportSize({ width, height: 1000 })
      for (const route of ['/login', '/register', '/user-home/market', '/user-home/products', '/user-home/orders', '/user-home/address', '/user-home/chat']) {
        if (route === '/login' || route === '/register') await page.evaluate(() => { localStorage.removeItem('TOKEN'); localStorage.removeItem('ROLE') })
        else await page.evaluate(data => { localStorage.setItem('TOKEN', data.token); localStorage.setItem('ROLE', data.role) }, login.data)
        await page.goto('http://127.0.0.1:21091' + route)
        await page.locator('.accessibility-toggle').waitFor()
        await page.waitForTimeout(700)
        assert.equal(new URL(page.url()).pathname, route, 'must test actual route, not a redirect')
        const layout = await page.evaluate(() => ({ viewport: innerWidth, content: document.documentElement.scrollWidth }))
        const axe = await new AxeBuilder({ page }).withTags(['wcag2a', 'wcag2aa', 'wcag21aa', 'wcag22aa']).analyze()
        const name = `${width}-${route.replaceAll('/', '_')}`
        await page.screenshot({ path: `${out}/${name}.png`, fullPage: true })
        results.push({ test: 'page-layout', width, route, scale: 2, ...layout, violations: axe.violations.map(v => ({ id: v.id, impact: v.impact, count: v.nodes.length, examples: v.nodes.slice(0,3).map(n=>({target:n.target,html:n.html})) })) })
      }
    }
    await page.goto('http://127.0.0.1:21091/user-home/address')
    await page.getByRole('button', { name: '新增收货地址' }).click()
    await page.getByRole('dialog').waitFor()
    const dialogScan = await new AxeBuilder({ page }).include('.el-dialog').analyze()
    results.push({ test: 'address-dialog', violations: dialogScan.violations.map(v => ({id:v.id, count:v.nodes.length, examples:v.nodes.map(n=>n.target)})) })
    await page.screenshot({ path: `${out}/320-address-dialog.png`, fullPage:true })
    await page.keyboard.press('Escape')
    await page.getByRole('dialog').waitFor({state:'hidden'})
    assert.equal(await page.evaluate(()=>document.activeElement.getAttribute('aria-label')), '新增收货地址')
    results.push({test:'dialog-focus-restored',passed:true})
    for (const width of [1440, 320]) {
      await page.setViewportSize({ width, height:1000 })
      for (const scale of [1, 2]) {
        await page.evaluate(value => localStorage.setItem('campus-font-scale', String(value)), scale)
        await page.goto('http://127.0.0.1:21091/user-home/market')
        await page.locator('.user-trigger').click()
        await page.getByRole('menuitem', {name:'退出登录'}).click()
        const box = page.locator('.logout-confirm')
        await box.waitFor()
        await page.waitForTimeout(300)
        const bounds = await box.boundingBox()
        assert.ok(bounds.width <= 440 && bounds.width <= width - 32)
        assert.ok(Math.abs(bounds.x + bounds.width / 2 - width / 2) < 3)
        assert.ok(Math.abs(bounds.y + bounds.height / 2 - 500) < 3)
        await box.getByRole('button', {name:'取消',exact:true}).click()
        await box.waitFor({state:'hidden'})
        assert.ok(await page.evaluate(()=>localStorage.getItem('TOKEN')))
        results.push({test:'centered-logout-cancel',width,scale,passed:true,box:bounds})
      }
    }
    // 验证跳过导航链接是第一个键盘焦点，且设置面板可通过键盘打开。
    await page.evaluate(() => { localStorage.removeItem('TOKEN'); localStorage.removeItem('ROLE') })
    await page.goto('http://127.0.0.1:21091/login')
    await page.locator('.auth-reading .accessibility-toggle').waitFor()
    await page.keyboard.press('Tab')
    assert.equal(await page.evaluate(() => document.activeElement.textContent), '跳到主要内容')
    await page.keyboard.press('Tab')
    assert.ok(await page.locator('.accessibility-toggle').evaluate(el => el === document.activeElement), 'keyboard focus must reach reading settings')
    await page.keyboard.press('Enter')
    await page.locator('.reading-panel:visible').waitFor()
    assert.equal(await page.locator('.accessibility-toggle').getAttribute('aria-expanded'), 'true')
    results.push({ test: 'keyboard-settings', passed: true })
    await page.getByRole('button', { name: '恢复默认' }).click()
    assert.equal(await page.locator('html').getAttribute('data-font-scale'), '1')
    results.push({ test: 'reset', passed: true })
    assert.deepEqual(errors, [])
    assert.deepEqual(results.filter(r => r.violations?.length), [], 'automated accessibility scan must pass for tested pages')
    assert.deepEqual(results.filter(r => r.content > r.viewport), [], 'tested pages must not overflow horizontally')
  } finally {
    fs.writeFileSync(`${out}/results.json`, JSON.stringify({ time: new Date().toISOString(), results, errors }, null, 2))
    await browser.close()
  }
  console.log(JSON.stringify(results, null, 2))
})().catch(error => { console.error(error); process.exitCode = 1 })
